BEGIN;

CREATE TABLE IF NOT EXISTS report_decision_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES reports(id),
  decision VARCHAR(16) NOT NULL CHECK (decision IN ('approved', 'rejected')),
  decision_note VARCHAR(2000) NOT NULL,
  decided_by BIGINT NOT NULL REFERENCES users(id),
  decided_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS report_decision_logs_report_idx
  ON report_decision_logs (report_id, decided_at DESC, id DESC);

INSERT INTO report_decision_logs
  (report_id, decision, decision_note, decided_by, decided_at)
SELECT r.id, r.status, COALESCE(r.decision_note, ''), r.decided_by, r.decided_at
FROM reports r
WHERE r.status IN ('approved', 'rejected')
  AND r.decided_by IS NOT NULL
  AND r.decided_at IS NOT NULL
  AND NOT EXISTS (
    SELECT 1
    FROM report_decision_logs d
    WHERE d.report_id = r.id
      AND d.decision = r.status
      AND d.decided_at = r.decided_at
  );

COMMIT;
